// Dev-server check: the co-op guest uplinks, draws and looses, and the host's sim sees it.
import puppeteer from 'puppeteer-core';
const base = process.argv[2] || 'http://localhost:5183';
const b = await puppeteer.launch({ executablePath: '/usr/bin/chromium', headless: true, protocolTimeout: 90000, args: ['--no-sandbox', '--mute-audio', '--use-gl=angle', '--use-angle=gl', '--ignore-gpu-blocklist'], defaultViewport: { width: 1280, height: 720 } });
const errs = [];
const open = async (tag) => { const p = await b.newPage(); p.on('pageerror', (e) => errs.push(tag + ': ' + e.message)); await p.goto(base + '/play.html'); await p.waitForFunction(() => document.getElementById('loading').classList.contains('hidden') && window.__dbg, { timeout: 60000 }); return p; };
const A = await open('host'), B = await open('guest');
const click = async (p, sel) => { await p.bringToFront(); await p.evaluate((s) => document.querySelector(s).click(), sel); };
const wait = (ms) => new Promise((r) => setTimeout(r, ms));
await click(A, '#m-coop'); await click(A, '#l-host');
await A.waitForFunction(() => document.getElementById('l-code').textContent.length === 6, { timeout: 25000 });
const code = await A.evaluate(() => document.getElementById('l-code').textContent);
await click(B, '#m-coop'); await B.evaluate((c) => { document.getElementById('l-input').value = c; }, code); await click(B, '#l-join');
await B.waitForFunction(() => !document.getElementById('hud').classList.contains('hidden'), { timeout: 30000 });
await wait(4000);
await A.bringToFront();
await A.evaluate(() => { const s = window.__dbg.sim; s.players[1].energy = 100; s.startWave(); });
await wait(6000);
await B.bringToFront(); await wait(800);
await B.keyboard.press('Space');
await wait(2500);
const g1 = await B.evaluate(() => { const p = window.__dbg.sim.players[1]; return { heroActive: p.heroActive, body: document.body.classList.contains('hero') }; });
const h1 = await A.evaluate(() => window.__dbg.sim.players[1].heroActive); // read the host in the background: switching tabs would pause the guest
console.log('guest uplinked: guest sees', JSON.stringify(g1), '| host sim says', h1);
// keep the guest page in front the whole time: a tab switch blurs it and drops the draw
await A.evaluate(() => { window.__log = { aim: 0, drawing: 0, arrows: 0, maxDraw: 0 }; const s = window.__dbg.sim; const orig = s.heroAim.bind(s); s.heroAim = (pi, d, x, y, z) => { if (pi === 1) { window.__log.aim++; if (d) window.__log.drawing++; } const r = orig(pi, d, x, y, z); if (pi === 1) window.__log.maxDraw = Math.max(window.__log.maxDraw, s.players[1].draw); return r; }; const push = s.events.push.bind(s.events); s.events.push = (...e) => { for (const x of e) if (x.k === 'arrow' && x.p === 1) window.__log.arrows++; return push(...e); }; });
await B.bringToFront(); await wait(500);
await B.mouse.move(640, 360);
console.log('guest before press:', JSON.stringify(await B.evaluate(() => { const e = document.elementFromPoint(640, 360); return { under: e ? e.tagName + '#' + e.id + '.' + e.className : null, lock: !!document.pointerLockElement, open: [...document.querySelectorAll('.overlay, .sheet-wrap, #cards, #pause, #tutor, #rotate')].filter((x) => !x.classList.contains('hidden') && getComputedStyle(x).display !== 'none').map((x) => x.id), intro: window.__dbg.view.introActive ? window.__dbg.view.introActive() : null }; })));
await B.mouse.down();
await wait(1500);
const mid = await A.evaluate(() => ({ ...window.__log }));
const gdraw = await B.evaluate(() => window.__dbg.sim.players[1].draw);
await B.mouse.up();
await wait(1500);
const end = await A.evaluate(() => ({ ...window.__log }));
console.log('while held: host log', JSON.stringify(mid), '| guest replica draw', gdraw);
console.log('after release: host log', JSON.stringify(end));
await b.close();
console.log(errs.length ? 'ERRORS:\n' + [...new Set(errs)].slice(0, 8).join('\n') : 'no page errors');
