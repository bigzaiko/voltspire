import puppeteer from 'puppeteer-core';
const b = await puppeteer.launch({ executablePath: '/usr/bin/chromium', headless: true, args: ['--no-sandbox', '--mute-audio', '--use-gl=angle', '--use-angle=gl', '--ignore-gpu-blocklist'], protocolTimeout: 60000, defaultViewport: { width: 1280, height: 720 } });
const open = async () => { const p = await b.newPage(); p.on('pageerror', (e) => console.log('[pageerror]', e.message)); p.on('console', (m) => { if (m.type() === 'error') console.log('[console]', m.text()); }); await p.goto('http://localhost:5184/play.html'); await p.waitForFunction(() => document.getElementById('loading').classList.contains('hidden'), { timeout: 60000 }); return p; };
const A = await open(), B = await open();
const T = (p, id) => p.evaluate((id) => document.getElementById(id).textContent, id);
const click = async (p, sel) => { await p.bringToFront(); await p.evaluate((sel) => document.querySelector(sel).click(), sel); };
await click(A, '#m-versus'); await click(A, '#l-host');
await A.waitForFunction(() => document.getElementById('l-code').textContent.length === 6, { timeout: 20000 });
const code = await T(A, 'l-code'); console.log('room', code);
await click(B, '#m-versus'); await B.evaluate((c) => { document.getElementById('l-input').value = c; }, code); await click(B, '#l-join');
await B.waitForFunction(() => !document.getElementById('hud').classList.contains('hidden'), { timeout: 30000 });
console.log('both in game; B vs panel visible:', await B.evaluate(() => !document.getElementById('vs').classList.contains('hidden')));
await new Promise((r) => setTimeout(r, 6000));
await A.bringToFront();
await click(A, '#vs-squads button');
await new Promise((r) => setTimeout(r, 900));
console.log('A gold after sending:', await T(A, 'gold'), '| A toasts:', await T(A, 'toasts'));
await B.bringToFront();
await new Promise((r) => setTimeout(r, 300));
console.log('B toasts:', await T(B, 'toasts'), '| B rival:', await T(B, 'vs-status'));
await A.bringToFront(); await new Promise((r) => setTimeout(r, 1500)); console.log('A rival:', await T(A, 'vs-status'));
await B.close();
await A.bringToFront();
await new Promise((r) => setTimeout(r, 14000));
console.log('A after B left:', await T(A, 'end-title'), '-', await T(A, 'end-sub'));
await b.close();
